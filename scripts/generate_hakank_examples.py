def combine(terms, operator, empty):
    terms = list(map(str, terms))
    if not terms:
        return empty
    if len(terms) == 1:
        return f"({terms[0]})"
    middle = len(terms) // 2
    return f"({combine(terms[:middle], operator, empty)} {operator} {combine(terms[middle:], operator, empty)})"


def total(terms):
    return combine(terms, "+", "0")


def conjunction(terms):
    return combine(terms, "&&", "true")


def disjunction(terms):
    return combine(terms, "||", "false")


def indicator(condition):
    return f"(if {condition} then 1 else 0)"


def share_decision_accesses(source: str, max_aliases: int = 128, min_uses: int = 8) -> str:
    """Share highly repeated pure projections without changing any decisions."""
    marker = "# Shared repeated immutable decision projections."
    if marker in source:
        return source
    access = re.compile(r"\(DecisionTree\.(intAt|boolAt|floatAt) (\d+) decisions(Int|Bool|Float)\)")
    counts = Counter(match[0] for match in access.finditer(source))
    selected = sorted(
        (text for text, count in counts.items() if count >= min_uses), key=lambda text: (-counts[text], text)
    )[:max_aliases]
    if not selected:
        return source
    aliases = {}
    definitions = []
    declared = set(re.findall(r"\bdef\s+([\w.]+)", source))
    for text in selected:
        match = access.fullmatch(text)
        assert match is not None
        method, index, kind = match.groups()
        name = f"_shared_decision_{method}_{index}"
        if name in declared:
            raise ValueError(f"Decision projection alias already declared: {name}")
        aliases[text] = name
        definitions.append(f"def {name} : {kind} := {text};")
    updated = access.sub(lambda match: aliases.get(match[0], match[0]), source)
    lines = updated.splitlines()
    position = max(i for i, line in enumerate(lines) if line.startswith("def decisions")) + 1
    lines[position:position] = ["", marker, *definitions]
    return "\n".join(lines) + "\n"


class Model:
    def __init__(self, name, instance, data=None):
        self.name = name
        self.instance = instance
        self.data = data or {}
        self.variables = {}
        self.value_types = {}
        self.constraints = []
        self.helpers = []
        self.compact = False
        self.sequences = []
        self.objective = "0"
        self.score_type = "Int"
        self.generator = "scripts/generate_hakank_examples.py"
        self.goal = "Find a feasible assignment (score 0)."
        self.optimum = 0

    def vector(self, prefix, count, lower, upper):
        names = [f"{prefix}{i}" for i in range(count)]
        self.variables.update({name: [lower, upper] for name in names})
        return names

    def sequence(self, values, kind="Int"):
        values = tuple(values)
        if not values:
            return "Vec.nil"
        entry = (kind, values)
        if entry not in self.sequences:
            self.sequences.append(entry)
        return f"sequence{self.sequences.index(entry)}_tail0"

    def distinct(self, values):
        return [f"Vec.allDifferent ({self.sequence(values)})"]

    def minimize(self, expression, goal, optimum):
        self.objective = expression
        self.goal = goal
        self.optimum = optimum

    def render(self, provenance):
        lines = [
            f"# {self.name}: {self.instance}",
            f"# GOAL: {self.goal}",
            f"# Source: {provenance['source_url']}",
            f"# Generated by {self.generator}; all decisions remain holes.",
            "# @require is a hard constraint, independent of the objective.",
            "",
            "import Vec;",
            "",
        ]
        lines += self.helpers
        replacements = {}
        reports = list(self.variables)
        if self.compact:
            lines.insert(lines.index("import Vec;") + 1, "import DecisionTree;")
            groups = {}
            for name, domain in self.variables.items():
                groups.setdefault(self.value_types.get(name, "Int"), []).append((name, domain))
            reports = []
            for kind, decisions in groups.items():
                root = f"decisions{kind}"
                reports.append(root)
                leaves = []
                for index, (name, (lo, hi)) in enumerate(decisions):
                    replacements[name] = f"(DecisionTree.{kind.lower()}At {index} {root})"
                    if kind == "Bool":
                        ty = "Bool"
                    else:
                        zero = "0.0" if kind == "Float" else "0"
                        lower = str(lo) if lo >= 0 else f"({zero} - {-lo})"
                        upper = str(hi) if hi >= 0 else f"({zero} - {-hi})"
                        ty = f"{{v:{kind} | {lower} <= v && v <= {upper}}}"
                    leaves.append(f"(DecisionTree.leaf (?h_{name} : {ty}))")

                def pack(values):
                    if len(values) == 1:
                        return values[0]
                    middle = len(values) // 2
                    return f"(DecisionTree.branch {middle} {pack(values[:middle])} {pack(values[middle:])})"

                lines.append(f"def {root} : (DecisionTree {kind}) := {pack(leaves)};")
        for name, (lo, hi) in [] if self.compact else self.variables.items():
            if self.value_types.get(name) == "Bool":
                lines.append(f"def {name} : Bool := ?h_{name};")
                continue
            kind = self.value_types.get(name, "Int")
            zero = "0.0" if kind == "Float" else "0"
            lower = str(lo) if lo >= 0 else f"({zero} - {-lo})"
            upper = str(hi) if hi >= 0 else f"({zero} - {-hi})"
            lines.append(f"def {name} : {{v:{kind} | {lower} <= v && v <= {upper}}} := ?h_{name};")
        for index, (kind, values) in enumerate(self.sequences):
            if len(values) <= 32:
                expression = "Vec.nil"
                for value in reversed(values):
                    expression = f"Vec.cons ({value}) ({expression})"
                lines.append(f"def sequence{index}_tail0 : (Vec {kind}) := {expression};")
                continue
            tail = "Vec.nil"
            for position in reversed(range(0, len(values), 32)):
                expression = tail
                for value in reversed(values[position : position + 32]):
                    expression = f"Vec.cons ({value}) ({expression})"
                name = f"sequence{index}_tail{position}"
                lines.append(f"def {name} : (Vec {kind}) := {expression};")
                tail = name
        lines += ["", "# Complete finite-instance constraints; Bool annotations keep verification local."]
        if self.compact:
            lines += ["def valid : Bool := " + conjunction(self.constraints) + ";"]
        else:
            lines += [f"def constraint{i} : Bool := {condition};" for i, condition in enumerate(self.constraints)]
            lines += [
                "def valid : Bool := " + conjunction([f"constraint{i}" for i in range(len(self.constraints))]) + ";"
            ]
        lines += [
            "",
            f"def objective : {self.score_type} := {self.objective};",
            f"def score : {self.score_type} := objective;",
            "",
            "@require(valid)",
            f"@minimize_{self.score_type.lower()}(score)",
            f"def benchmark : {self.score_type} := score;",
            "",
            "def main (_:Int) : Unit :=",
            "    let report := print score in",
        ]
        lines += [f"    let report{i} := print {name} in" for i, name in enumerate(reports)]
        lines += ["    unit;", ""]
        rendered = "\n".join(lines)
        if replacements:
            names = "|".join(map(re.escape, replacements))
            rendered = re.sub(r"\b(?:" + names + r")\b", lambda match: replacements[match[0]], rendered)
        return share_decision_accesses(rendered)


def models():
    result = []

    def new(name, instance, data=None):
        model = Model(name, instance, data)
        result.append(model)
        return model

    m = new("send_more_money", "base 10, eight distinct digits")
    digits = list("sendmory")
    m.variables.update({letter: [1 if letter in "sm" else 0, 9] for letter in digits})
    left = total(["1000 * s", "100 * e", "10 * n", "d", "1000 * m", "100 * o", "10 * r", "e"])
    right = total(["10000 * m", "1000 * o", "100 * n", "10 * e", "y"])
    m.constraints = m.distinct(digits) + [f"{left} = {right}"]

    m = new("nqueens", "8 queens, one per column", {"n": 8})
    q = m.vector("q", 8, 0, 7)
    m.constraints = m.distinct(q)
    for i, j in combinations(range(8), 2):
        m.constraints += [f"{q[i]} - {q[j]} != (0 - {j - i})", f"{q[i]} - {q[j]} != {j - i}"]

    for name, size, clues, blocks in [
        ("sudoku", 4, [[1, 0, 0, 4], [0, 4, 1, 0], [0, 1, 4, 0], [4, 0, 0, 1]], True),
        (
            "quasigroup_completion",
            5,
            [[1, 0, 0, 0, 4], [0, 5, 0, 0, 0], [4, 0, 0, 2, 0], [0, 4, 0, 0, 0], [0, 0, 5, 0, 1]],
            False,
        ),
    ]:
        m = new(
            name,
            f"{size}x{size} completion" + (" (reduced Sudoku instance)" if blocks else " (upstream default)"),
            {"size": size, "clues": clues},
        )
        cells = m.vector("x", size * size, 1, size)
        for i in range(size):
            m.constraints += m.distinct(cells[i * size : (i + 1) * size])
            m.constraints += m.distinct(cells[i::size])
            for j in range(size):
                if clues[i][j]:
                    m.constraints.append(f"{cells[i * size + j]} = {clues[i][j]}")
        if blocks:
            for row in (0, 2):
                for col in (0, 2):
                    m.constraints += m.distinct([cells[(row + i) * size + col + j] for i in range(2) for j in range(2)])

    m = new("magic_square", "normal 3x3 square, line sum 15", {"size": 3})
    x = m.vector("x", 9, 1, 9)
    m.constraints = m.distinct(x) + [f"{total(x[i::3])} = 15" for i in range(3)]
    m.constraints += [f"{total(x[i * 3 : (i + 1) * 3])} = 15" for i in range(3)]
    m.constraints += [f"{total(x[0::4])} = 15", f"{total([x[2], x[4], x[6]])} = 15"]

    m = new("all_interval", "series of size 5 (reduced instance)", {"n": 5})
    x = m.vector("x", 5, 1, 5)
    d = m.vector("d", 4, 1, 4)
    m.constraints = (
        m.distinct(x)
        + m.distinct(d)
        + [f"{d[i]} = {x[i + 1]} - {x[i]} || {d[i]} = {x[i]} - {x[i + 1]}" for i in range(4)]
    )
    m.constraints += ["x0 < x4", "d0 < d1"]

    m = new("all_different_except_0", "five values in 0..5; repeated zeros allowed")
    x = m.vector("x", 5, 0, 5)
    m.constraints = [f"{a} = 0 || {b} = 0 || {a} != {b}" for a, b in combinations(x, 2)]

    m = new("among", "exactly three of five values belong to {1,5,8}")
    x = m.vector("x", 5, 1, 8)
    m.constraints = [f"{total([indicator(disjunction([f'{v} = {k}' for k in [1, 5, 8]])) for v in x])} = 3"]

    for name, cost in [
        ("assignment", [[14, 5, 8, 7, 15], [2, 12, 6, 5, 3], [7, 8, 3, 9, 7], [2, 4, 6, 10, 1]]),
        ("ski_assignment", [[abs(person - ski) for ski in [1, 2, 5, 7, 13, 21]] for person in [3, 4, 7, 11, 18]]),
    ]:
        rows, cols = len(cost), len(cost[0])
        m = new(name, f"{rows} people, {cols} choices (upstream data)", {"cost": cost})
        x = m.vector("x", rows * cols, 0, 1)
        m.constraints = [f"{total(x[i * cols : (i + 1) * cols])} = 1" for i in range(rows)]
        m.constraints += [f"{total(x[j::cols])} <= 1" for j in range(cols)]
        m.minimize(
            total([f"{cost[i][j]} * {x[i * cols + j]}" for i in range(rows) for j in range(cols)]),
            "Minimize total assignment cost/disparity.",
            11 if name == "assignment" else 7,
        )

    distances = [
        [0, 10, 20, 30, 30, 20],
        [10, 0, 25, 35, 20, 10],
        [20, 25, 0, 15, 30, 20],
        [30, 35, 15, 0, 15, 25],
        [30, 20, 30, 15, 0, 14],
        [20, 10, 20, 25, 14, 0],
    ]
    m = new("set_covering", "six fire-station cities; maximum distance 15", {"distances": distances})
    x = m.vector("x", 6, 0, 1)
    m.constraints = [f"{total([x[j] for j in range(6) if distances[i][j] <= 15])} >= 1" for i in range(6)]
    m.minimize(total(x), "Minimize the number of fire stations covering all cities.", 2)

    for name, weights, target, upper in [
        ("subset_sum", [16, 17, 23, 24, 39, 40], 100, 6),
        ("xkcd", [215, 275, 335, 355, 420, 580], 1505, 10),
    ]:
        m = new(name, f"nonnegative counts, total {target} (upstream data)", {"weights": weights, "target": target})
        x = m.vector("x", len(weights), 0, upper)
        m.constraints = [f"{total([f'{w} * {v}' for w, v in zip(weights, x)])} = {target}"]

    values = [15, 100, 90, 60, 40, 15, 10, 1, 12, 12, 100]
    weights = [2, 20, 20, 30, 40, 30, 60, 10, 21, 12, 2]
    m = new(
        "knapsack",
        "11 binary items, capacity 102 (upstream data)",
        {"values": values, "weights": weights, "capacity": 102},
    )
    x = m.vector("x", len(values), 0, 1)
    m.constraints = [f"{total([f'{w} * {v}' for w, v in zip(weights, x)])} <= 102"]
    m.minimize(
        f"{sum(values)} - {total([f'{w} * {v}' for w, v in zip(values, x)])}",
        f"Maximize item value (minimize {sum(values)} minus value).",
        sum(values) - 378,
    )

    m = new(
        "bin_packing", "weights [4,3,1], capacity 4 (small upstream example)", {"weights": [4, 3, 1], "capacity": 4}
    )
    x = m.vector("x", 3, 0, 2)
    for b in range(3):
        terms = [f"{w} * {indicator(f'{v} = {b}')}" for w, v in zip([4, 3, 1], x)]
        m.constraints.append(f"{total(terms)} <= 4")
    m.minimize(
        total([indicator(disjunction([f"{v} = {b}" for v in x])) for b in range(3)]), "Minimize occupied bins.", 2
    )

    m = new("langford", "k=3, positions of two copies (reduced instance)", {"k": 3})
    p = m.vector("p", 6, 0, 5)
    m.constraints = m.distinct(p) + [f"{p[i + 3]} = {p[i]} + {i + 2}" for i in range(3)]

    edges = [(2, 0), (2, 5), (2, 3), (5, 3), (5, 0), (0, 4), (0, 3), (3, 4), (3, 1)]
    m = new("map_coloring", "Belgium/Denmark/France/Germany/Netherlands/Luxembourg, four colors", {"edges": edges})
    x = m.vector("x", 6, 1, 4)
    m.constraints = ["x0 = 1"] + [f"{x[i]} != {x[j]}" for i, j in edges]

    m = new("golomb_ruler", "four ordered marks, upper bound 10 (reduced instance)", {"n": 4})
    x = m.vector("x", 4, 0, 10)
    m.constraints = ["x0 = 0"] + [f"{x[i]} < {x[i + 1]}" for i in range(3)]
    m.constraints += m.distinct([f"({x[j]} - {x[i]})" for i, j in combinations(range(4), 2)])
    m.minimize("x3", "Minimize ruler length with distinct pairwise distances.", 6)

    m = new("magic_sequence", "length 5 (one of upstream's sizes 1..19)", {"n": 5})
    x = m.vector("x", 5, 0, 4)
    m.constraints = [f"{x[i]} = {total([indicator(f'{v} = {i}') for v in x])}" for i in range(5)]

    m = new("seseman", "3x3 border, each side sums to 9 (upstream default)")
    x = m.vector("x", 8, 1, 9)
    m.constraints = [f"{total([x[i] for i in side])} = 9" for side in [(0, 1, 2), (0, 3, 5), (2, 4, 7), (5, 6, 7)]]

    m = new("rabbits", "nine rabbits/pheasants with 24 legs (upstream data)")
    m.variables = {"rabbits": [0, 9], "pheasants": [0, 9]}
    m.constraints = ["rabbits + pheasants = 9", "4 * rabbits + 2 * pheasants = 24"]

    duration, resource = [16, 6, 13, 7, 5, 18, 4], [2, 9, 3, 7, 10, 1, 11]
    m = new(
        "schedule1",
        "seven cumulative tasks, capacity 13, integer starts 1..30 (upstream data)",
        {"duration": duration, "resource": resource, "capacity": 13},
    )
    starts = m.vector("s", 7, 1, 30)
    m.variables["makespan"] = [1, 50]
    m.constraints = [f"{s} + {d} <= makespan" for s, d in zip(starts, duration)]
    # Nonnegative resource usage can increase only at a task start.
    # Checking all seven start events is equivalent to every integer slot.
    for time in starts:
        terms = [
            f"{r} * {indicator(f'{s} <= {time} && {time} < {s} + {d}')}" for s, d, r in zip(starts, duration, resource)
        ]
        m.constraints.append(f"{total(terms)} <= 13")
    m.minimize("makespan", "Minimize completion time without exceeding resource capacity.", 23)

    rows, cols = [0, 0, 8, 2, 6, 4, 5, 3, 7, 0, 0], [0, 0, 7, 1, 6, 3, 4, 5, 2, 7, 0, 0]
    m = new(
        "discrete_tomography", "11x12 binary image with upstream default row/column sums", {"rows": rows, "cols": cols}
    )
    x = m.vector("x", len(rows) * len(cols), 0, 1)
    m.constraints = [f"{total(x[i * len(cols) : (i + 1) * len(cols)])} = {count}" for i, count in enumerate(rows)]
    m.constraints += [f"{total(x[j :: len(cols)])} = {count}" for j, count in enumerate(cols)]

    m = new(
        "traffic_lights",
        "CSPLib 016, four vehicle/pedestrian pairs",
        {"allowed": [[0, 0, 2, 2], [1, 0, 3, 0], [2, 2, 0, 0], [3, 0, 1, 0]]},
    )
    v, p = m.vector("v", 4, 0, 3), m.vector("p", 4, 0, 3)
    for i in range(4):
        terms = [v[i], p[i], v[(i + 1) % 4], p[(i + 1) % 4]]
        m.constraints.append(
            disjunction([conjunction([f"{t} = {value}" for t, value in zip(terms, row)]) for row in m.data["allowed"]])
        )

    m = new("nvalue", "five values in 1..5, synthesize their distinct-value count")
    x = m.vector("x", 5, 1, 5)
    m.variables["count"] = [0, 5]
    m.constraints = [f"count = {total([indicator(disjunction([f'{v} = {k}' for v in x])) for k in range(1, 6)])}"]
    return result


def generate():
    manifest = json.loads((SUITE / "manifest.json").read_text())
    provenance = {entry["name"]: entry for entry in manifest["models"]}
    for model in models():
        entry = provenance[model.name]
        entry.update(
            instance=model.instance,
            variables=model.variables,
            data=model.data,
            goal=model.goal,
            expected_score=model.optimum,
        )
        (SUITE / f"{model.name}.ae").write_text(model.render(entry), encoding="utf-8")
    (SUITE / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    generate()
