"""Noisy-example synthesis keeps contracts hard and minimizes regularized risk."""

from time import monotonic

from aeon.backend.evaluator import eval as aeon_eval
from aeon.core.multiplicity import MOmega
from aeon.core.substitutions import substitution, substitution_in_type
from aeon.core.terms import Abstraction, Application, Hole, Let, Literal, Var
from aeon.core.types import AbstractionType, RefinedType, t_bool, t_float, t_int, t_string
from aeon.synthesis.api import Synthesizer, UnsupportedSynthesisGoal
from aeon.synthesis.fitness_eval import set_program_tail, without_main_placeholder
from aeon.synthesis.identification import get_holes, iterate_top_level
from aeon.synthesis.modules.enumerative import iter_candidates
from aeon.synthesis.modules.noisy.model import Config, Dataset
from aeon.synthesis.modules.noisy.search import run_search
from aeon.synthesis.modules.noisy.structure import complexity
from aeon.synthesis.scope import fitness_relevant_names
from aeon.typechecking.typeinfer import check_type


BASES = {t_bool: bool, t_int: int, t_float: float, t_string: str}


def base(ty):
    return ty.type if isinstance(ty, RefinedType) else ty


class NoisySynthesizer(Synthesizer):
    def __init__(self, seed=0, config=None):
        self.seed = seed
        self.config = Config.from_env() if config is None else config
        self.last_report = None

    def synthesize_source(self, ctx, tyctx, ectx, program, function, hole, ty, metadata, validate, budget, ui):
        started = monotonic()
        self.last_report = None
        program = without_main_placeholder(program)
        if get_holes(program) != [hole] and set(get_holes(program)) != {hole}:
            raise UnsupportedSynthesisGoal("noisy requires exactly one open body hole")
        entry = metadata.get(function, {})
        examples = entry.get("examples", [])
        pairs = entry.get("io_examples", [])
        if len(pairs) > self.config.max_rows:
            raise UnsupportedSynthesisGoal("noisy dataset exceeds AEON_NOISY_MAX_ROWS")
        if not examples or len(pairs) != len(examples) or entry.get("example_io_miss"):
            raise UnsupportedSynthesisGoal("noisy requires every example to be a scalar literal I/O equality")
        for name, data in metadata.items():
            if not isinstance(data, dict):
                continue
            if "property" in data or data.get("cluster") or data.get("recursion"):
                raise UnsupportedSynthesisGoal("noisy does not support property, cluster or recursion goals")
            goals = data.get("goals", [])
            if len(goals) != len(data.get("examples", [])) or any(g.kind != "expression" for g in goals):
                raise UnsupportedSynthesisGoal("noisy supports only the objectives generated by @example")
            if name != function and data.get("examples"):
                raise UnsupportedSynthesisGoal("noisy requires examples attached only to the synthesis target")
        definitions = {r.var_name: r.var_value for r in iterate_top_level(program)}
        declaration = next(r for r in iterate_top_level(program) if r.var_name == function)
        signature, body = declaration.var_type, declaration.var_value
        parameters = []
        while isinstance(signature, AbstractionType) and isinstance(body, Abstraction):
            if signature.multiplicity is not MOmega or base(signature.var_type) not in BASES:
                raise UnsupportedSynthesisGoal("noisy requires unrestricted scalar parameters")
            parameters.append((body.var_name, signature.var_name, signature.var_type))
            signature, body = signature.type, body.body
        if [n for n, _, _ in parameters] != entry.get("io_params", []) or base(signature) not in BASES:
            raise UnsupportedSynthesisGoal("noisy requires a scalar body hole with declared I/O parameter order")
        while isinstance(body, Let):
            definitions[body.var_name] = body.var_value
            body = body.body
        if not isinstance(body, Hole) or body.name != hole or base(ty) not in BASES:
            raise UnsupportedSynthesisGoal("noisy supports a single body hole, optionally under lexical let bindings")
        dataset = Dataset.from_pairs(pairs, len(parameters))
        for row in dataset.rows:
            if type(row.expected) is not BASES[base(signature)] or any(
                type(value) is not BASES[base(parameter_type)]
                for value, (_, _, parameter_type) in zip(row.inputs, parameters)
            ):
                raise UnsupportedSynthesisGoal(f"Observation {row.id} has a scalar type mismatch")
        inputs = {n for n, _, _ in parameters}
        definitions.pop(function, None)
        hidden = fitness_relevant_names(metadata)

        def skip(name):
            if name == function or name.name in hidden:
                return True
            try:
                complexity(Var(name), inputs, definitions)
                return False
            except Exception:
                return True

        def domain_check():
            for row in dataset.rows:
                previous = []
                for value, (_, formal, parameter_type) in zip(row.inputs, parameters):
                    expected = parameter_type
                    for old, literal in previous:
                        expected = substitution_in_type(expected, literal, old)
                    literal = Literal(value, base(parameter_type))
                    if not check_type(ctx, literal, expected):
                        return False
                    previous.append((formal, literal))
            return True

        def probe(candidate, values):
            completed = substitution(program, candidate, hole)
            call = Var(function)
            for value, (_, _, parameter_type) in zip(values, parameters):
                call = Application(call, Literal(value, base(parameter_type)))
            return aeon_eval(set_program_tail(completed, call), ectx)

        remaining = budget - (monotonic() - started)
        stream = iter_candidates(
            tyctx,
            base(ty),
            function,
            metadata,
            self.config.max_depth,
            budget=max(0, remaining),
            skip=skip,
            max_expansions=self.config.max_expansions,
            max_worklist=self.config.max_worklist,
        )
        try:
            result, report = run_search(
                dataset,
                self.config,
                self.seed,
                stream,
                validate,
                probe,
                inputs,
                definitions,
                ui,
                remaining,
                domain_check,
            )
            self.last_report = report
            ui.report(report.as_dict())
            ui.end(result, [report.objective])
            return result
        except Exception:
            ui.end(None, None)
            raise

    def synthesize(self, *args, **kwargs):
        raise UnsupportedSynthesisGoal("noisy needs source-level examples; use synthesize_holes")
