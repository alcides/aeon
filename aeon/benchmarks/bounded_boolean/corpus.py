"""Pinned BNSynth inventory and deterministic ordinary-Aeon translation."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import urllib.request

from aeon.benchmarks.bounded_boolean.verilog import Circuit, Expr, VerilogError, parse

REVISION = "12a12dab2f3ed8ff92f88dc8a915826a8f9fe6d4"
REPOSITORY = "https://github.com/rrlcs/bnsynth"
ROOT = Path(__file__).resolve().parents[3] / "examples/synthesis/boolean_bounded/bnsynth"
SOURCE = Path("benchmarks/custom_and_lut")
PAPER_SCHEDULE = ((1, 60), (5, 120), (20, 120), (50, 180), (500, 300), (1000, 600))


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def ae_name(name: str) -> str:
    # Injective encoding, including escaped dollars and underscores.
    return "v" + "".join(c if c.isalnum() else f"_{ord(c):02x}_" for c in name)


def expression(expr: Expr) -> str:
    op, *args = expr
    if op == "bool":
        return str(args[0]).lower()
    if op == "var":
        return ae_name(args[0])
    if op == "not":
        return f"(!{expression(args[0])})"
    operator = {"and": "&&", "or": "||", "xor": "!="}[op]
    return f"({expression(args[0])} {operator} {expression(args[1])})"


def emit(circuit: Circuit, case: str, bound: int = 5) -> str:
    if type(bound) is not int or bound < 0:
        raise ValueError("bound must be a nonnegative integer")
    params = " ".join(f"({ae_name(n)}:Bool)" for n in circuit.x)
    text = [
        f"# BNSynth {case}; upstream {REVISION}",
        "# Partial relation: forall X,Y. F(X,Y) --> F(X, choose(X)).",
        "# Generated by python -m aeon.benchmarks.bounded_boolean import; do not edit.",
    ]
    # Define unknowns before the relation, so relation logic/reference answers
    # cannot become synthesis components. Every backend sees the same source.
    for n in circuit.y:
        text += [f"@bounded_cnf({bound})", f"def choose_{ae_name(n)} {params} : Bool := ?hole_{ae_name(n)};", ""]
    relation_params = " ".join(f"({ae_name(n)}:Bool)" for n in circuit.inputs)
    text.append(f"def relation {relation_params} : Bool :=")
    for n, expr in circuit.assignments:
        text.append(f"    let {ae_name(n)} := {expression(expr)} in")
    text.append(f"    {ae_name(circuit.outputs[0])};")
    before = "relation " + " ".join(ae_name(n) for n in circuit.inputs)
    values = {n: f"(choose_{ae_name(n)} {' '.join(ae_name(x) for x in circuit.x)})" for n in circuit.y}
    after = "relation " + " ".join(values.get(n, ae_name(n)) for n in circuit.inputs)
    text += [
        "",
        "@property(32)",
        f"def skolem_law {relation_params} : Bool :=",
        f"    ({before.strip()}) --> ({after.strip()});",
        "",
    ]
    return "\n".join(text)


def load_case(case: dict, root: Path = ROOT) -> Circuit:
    return parse(
        (root / "upstream" / case["source"]).read_text(),
        (root / "upstream" / case["y_file"]).read_text(),
        case["source"],
    )


def regenerate(root: Path = ROOT, bound: int = 5) -> dict:
    upstream = root / "upstream"
    files = {
        p.relative_to(upstream).as_posix(): {"sha256": digest(p.read_bytes()), "bytes": p.stat().st_size}
        for p in sorted(upstream.rglob("*"))
        if p.is_file()
    }
    specs = sorted((upstream / SOURCE).glob("*.v"))
    y_files = sorted((upstream / SOURCE / "Yvarlist").glob("*_varstoelim.txt"))
    cases = []
    used = set()
    (root / "cases").mkdir(parents=True, exist_ok=True)
    for path in specs:
        y_path = path.parent / "Yvarlist" / f"{path.stem}_varstoelim.txt"
        case = {
            "id": path.stem,
            "source": path.relative_to(upstream).as_posix(),
            "y_file": y_path.relative_to(upstream).as_posix(),
            "bound": bound,
        }
        try:
            circuit = load_case(case, root)
            used.add(y_path)
            destination = root / "cases" / f"{path.stem}.ae"
            source = emit(circuit, path.stem, bound)
            destination.write_text(source)
            case.update(
                status="imported",
                aeon=destination.relative_to(root).as_posix(),
                aeon_sha256=digest(source.encode()),
                inputs=list(circuit.x),
                outputs=list(circuit.y),
                variable_order=list(circuit.inputs),
                unused_declarations=list(circuit.unused),
                functions={n: f"choose_{ae_name(n)}" for n in circuit.y},
            )
        except (VerilogError, FileNotFoundError) as exc:
            case.update(status="unsupported", reason=str(exc))
        cases.append(case)
    # Reference-solution files are deliberately excluded from benchmark inputs.
    inventory = {
        "specifications": len(specs),
        "benchmark_y_lists": len(y_files),
        "matched": len(used),
        "orphan_y_lists": [p.relative_to(upstream).as_posix() for p in y_files if p not in used],
    }
    provenance = root / "inventory-provenance.json"
    if provenance.exists():
        refs = json.loads(provenance.read_text())["excluded_reference_lists"]
        inventory["excluded_reference_y_lists"] = len(refs)
        inventory["repository_y_lists_total"] = len(y_files) + len(refs)
    result = {
        "schema_version": 1,
        "repository": REPOSITORY,
        "revision": REVISION,
        "license": "MIT",
        "format": "CNF",
        "semantics": "forall X,Y. F(X,Y) => F(X,psi(X))",
        "default_bound": bound,
        "paper_schedule": PAPER_SCHEDULE,
        "inventory": inventory,
        "files": files,
        "cases": cases,
    }
    (root / "manifest.json").write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    return result


def verify_manifest(root: Path = ROOT) -> dict:
    manifest = json.loads((root / "manifest.json").read_text())
    actual_files = {p.relative_to(root / "upstream").as_posix() for p in (root / "upstream").rglob("*") if p.is_file()}
    if actual_files != set(manifest["files"]):
        raise ValueError("vendored source inventory differs from manifest")
    for path, expected in manifest["files"].items():
        if digest((root / "upstream" / path).read_bytes()) != expected["sha256"]:
            raise ValueError(f"source hash mismatch: {path}")
    for case in manifest["cases"]:
        if case["status"] == "imported" and digest((root / case["aeon"]).read_bytes()) != case["aeon_sha256"]:
            raise ValueError(f"generated hash mismatch: {case['id']}")
    return manifest


def fetch(root: Path = ROOT) -> None:
    """Explicit network operation; download only files pinned in the manifest."""
    manifest = json.loads((root / "manifest.json").read_text())
    for path, expected in manifest["files"].items():
        destination = root / "upstream" / path
        if destination.exists() and digest(destination.read_bytes()) == expected["sha256"]:
            continue
        data = urllib.request.urlopen(
            f"https://raw.githubusercontent.com/rrlcs/bnsynth/{REVISION}/{path}", timeout=30
        ).read()
        if digest(data) != expected["sha256"]:
            raise ValueError(f"download hash mismatch: {path}")
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)
